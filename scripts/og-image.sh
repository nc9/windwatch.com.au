#!/usr/bin/env bash
# Regenerate public/og-bg.png (clean map, no panels) + api/lib/og-bg.ts (base64
# inlined for api/og.tsx) from a running `bun run preview` (port 4173).
# Needs agent-browser + imagemagick. Not used at runtime.
set -euo pipefail
tmp=$(mktemp -d)
agent-browser set viewport 1600 840
agent-browser open http://localhost:4173
sleep 7
agent-browser eval 'document.querySelectorAll(".pointer-events-auto,.maplibregl-control-container,button").forEach(e=>e.style.display="none")'
sleep 1
agent-browser screenshot "$tmp/shot.png"
magick "$tmp/shot.png" -resize 1200x630! -colors 128 PNG8:public/og-bg.png
agent-browser close
{
	echo "// Generated by scripts/og-image.sh from public/og-bg.png"
	echo "export const OG_BG = \"data:image/png;base64,$(base64 < public/og-bg.png | tr -d '\n')\""
} > api/lib/og-bg.ts
